#[inline]
const fn gcd_u32(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        let r = a % b;
        a = b;
        b = r;
    }
    a
}

/// Derives the 20-byte `hash58` HMAC-SHA1 key from an 8-byte big-endian FireWire GUID.
///
/// Note: When either byte of a 2-byte GUID pair is zero, the pair's LCM evaluates to `1`
/// (not `0`), matching iPod Classic 6G/7G firmware behavior.
#[must_use]
pub fn derive_hash58_key(guid: FirewireGuid) -> [u8; 20] {
    let bytes = guid.as_bytes();
    let mut y = [0u8; 16];

    for i in 0..4 {
        let a = u32::from(bytes[2 * i]);
        let b = u32::from(bytes[2 * i + 1]);
        let lcm = if a == 0 || b == 0 {
            1
        } else {
            (a * b) / gcd_u32(a, b)
        };
        let hi = ((lcm >> 8) & 0xFF) as usize;
        let lo = (lcm & 0xFF) as usize;
        y[4 * i] = AES_SBOX[hi];
        y[4 * i + 1] = AES_INV_SBOX[hi];
        y[4 * i + 2] = AES_SBOX[lo];
        y[4 * i + 3] = AES_INV_SBOX[lo];
    }

    let mut hasher = Sha1::new();
    hasher.update(HASH58_FIXED_SEED);
    hasher.update(y);
    hasher.finalize().into()
}

/// Computes the 20-byte `hash58` HMAC-SHA1 digest over `buf` without allocating or copying `buf`.
///
/// Zeroed ranges during digest computation:
/// - `0x18..0x20` (`db_id`, 8 bytes)
/// - `0x32..0x46` (`unk_0x32`, 20 bytes)
/// - `0x58..0x6C` (`hash58` output slot, 20 bytes)
///
/// Offset `0x30..0x32` (`hashing_scheme`) is hashed as `1u16` (little-endian), while `0x70..0xA0`
/// (`hash72` region) is hashed untouched so dual-signed databases match Apple iTunes.
pub fn compute_hash58(buf: &[u8], guid: FirewireGuid) -> Result<[u8; 20], CryptoError> {
    if buf.len() < MIN_MHBD_SIGNING_LEN {
        return Err(CryptoError::BufferTooSmall {
            actual: buf.len(),
            minimum: MIN_MHBD_SIGNING_LEN,
        });
    }
    if &buf[0..4] != MHBD_MAGIC {
        return Err(CryptoError::InvalidMagic);
    }

    let key = derive_hash58_key(guid);
    let mut mac = HmacSha1::new_from_slice(&key).expect("HMAC-SHA1 accepts 20-byte keys");

    mac.update(&buf[0x00..0x18]);
    mac.update(&[0u8; 8]); // 0x18..0x20: db_id zeroed
    mac.update(&buf[0x20..0x30]);
    mac.update(&1u16.to_le_bytes()); // 0x30..0x32: hashing_scheme = 1
    mac.update(&[0u8; 20]); // 0x32..0x46: unk_0x32 zeroed
    mac.update(&buf[0x46..0x58]);
    mac.update(&[0u8; 20]); // 0x58..0x6C: hash58 slot zeroed
    mac.update(&buf[0x6C..]);

    Ok(mac.finalize().into_bytes().into())
}

/// Signs `buf` in place with `hash58`, setting `mhbd[0x30..0x32] = 1` and writing the
/// 20-byte digest to `mhbd[0x58..0x6C]`. Preserves `db_id` and `unk_0x32`.
pub fn sign_hash58(buf: &mut [u8], guid: FirewireGuid) -> Result<[u8; 20], CryptoError> {
    let digest = compute_hash58(buf, guid)?;
    buf[0x30..0x32].copy_from_slice(&1u16.to_le_bytes());
    buf[0x58..0x6C].copy_from_slice(&digest);
    Ok(digest)
}

/// Verifies that `buf` carries a valid `hash58` signature for `guid`.
pub fn verify_hash58(buf: &[u8], guid: FirewireGuid) -> Result<bool, CryptoError> {
    if buf.len() < MIN_MHBD_SIGNING_LEN {
        return Err(CryptoError::BufferTooSmall {
            actual: buf.len(),
            minimum: MIN_MHBD_SIGNING_LEN,
        });
    }
    if &buf[0..4] != MHBD_MAGIC {
        return Err(CryptoError::InvalidMagic);
    }
    let scheme = u16::from_le_bytes([buf[0x30], buf[0x31]]);
    if scheme != 1 {
        return Ok(false);
    }
    let expected = compute_hash58(buf, guid)?;
    Ok(constant_time_eq_20(&buf[0x58..0x6C], &expected))
}

#[inline]
fn constant_time_eq_20(lhs: &[u8], rhs: &[u8; 20]) -> bool {
    if lhs.len() != 20 {
        return false;
    }
    let mut diff = 0u8;
    for i in 0..20 {
        diff |= lhs[i] ^ rhs[i];
    }
    diff == 0
}
